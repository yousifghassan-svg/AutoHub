function item(
  partial: Omit<ManagedListing, 'stats' | 'currencyCode' | 'imageUrl' | 'description'> & {
    views?: number;
    favorites?: number;
    description?: string;
  },
): ManagedListing {
  return {
    currencyCode: 'IQD',
    imageUrl: null,
    description: partial.description ?? 'وصف تجريبي',
    stats: {
      views: partial.views ?? 0,
      favorites: partial.favorites ?? 0,
      phoneClicks: null,
      whatsappClicks: null,
      shares: null,
    },
    ...partial,
  };
}

